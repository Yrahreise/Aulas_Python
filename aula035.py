"""
Repetições
while (enquanto)
Executa uma ação enquanto uma condição for verdadeira
Loop infinito: um loop que não tem fim, ou seja, a condição nunca se torna falsa
"""

contador = 0 # contador é uma variável que controla o número de vezes que o loop será executado

while contador <= 10: # enquanto contador for menor ou igual a 10, o loop será executado
    print(contador) # imprime o valor da variável contador a cada iteração do loop
    contador = contador + 1  # contador recebe o valor de contador + 1 (contador é incrementado em 1 a cada iteração)

print('Acabou')


